<?php
/*
4. Палиндром: Напишите функцию, которая рекурсивно проверяет, является ли заданная строка палиндромом.
Палиндром — это слово или строка, которая читается одинаково слева направо и справа налево.
*/

// Рекурсивная функция проверки палиндрома
function isPalindrome($str) {

    if (mb_strlen($str) <= 1) { // проверка кол-во символов в строке
        return true;
    }
    $first = mb_substr($str, 0, 1); // первый символ
    $last = mb_substr($str, -1); // последний символ

    // Если символы не совпадают
    if ($first != $last) {
        return false;
    }

    $str = mb_substr($str, 1, mb_strlen($str) - 2); // записывает строку без первого и последнего символов
    return isPalindrome($str);
}

$str = readline("Введите строку: ");
$result = isPalindrome($str);

if ($result) {
    echo "Строка является палиндромом.\n";
} else {
    echo "Строка не является палиндромом.\n";
}