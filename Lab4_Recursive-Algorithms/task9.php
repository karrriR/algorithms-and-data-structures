function tower($n, $from, $to, $aux) {
    if ($n == 0) { // если дисков не осталось
        return;
    }

    tower($n - 1, $from, $aux, $to); // перемещение n - 1 диск на вспомогательный стержень

    echo "Переместить диск $n со стержня $from на стержень $to\n";

    tower($n - 1, $aux, $to, $from); // перемещение n - 1 диск со вспомогательного на целевой стержень
}

$n = (int) readline("Введите количество дисков: ");

tower($n, "A", "C", "B");