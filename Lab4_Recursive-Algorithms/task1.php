<?php
/*
1. Факториал числа: Напишите функцию, которая рекурсивно вычисляет факториал заданного числа n.
*/

// Рекурсивная функция вычисления факториала
function factorial(int $n) {
    if ($n == 0) { //условие остановки рекурсии
        return 1;
    }
    return $n * factorial($n - 1); //возвращение числа
}


do {
    $n = (int) readline("Введите число N: ");

    if ($n < 0) {
        echo "Ошибка! Число должно быть неотрицательным.\n";
    }

} while ($n < 0);

$result = factorial($n);

echo "$n! = $result\n";