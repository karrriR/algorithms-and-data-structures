// Рекурсивная функция вычисления числа Фибоначчи
function fibonacci(int $n) {
    if ($n == 0) { // условие остановки рекурсии
        return 0;
    }
    if ($n == 1) { //условие остановки рекурсии
        return 1;
    }

    return fibonacci($n - 1) + fibonacci($n - 2); // возвращает значение
}


do {
    $n = (int) readline("Введите номер числа Фибоначчи: ");

    if ($n < 0) {
        echo "Ошибка! Номер должен быть неотрицательным.\n";
    }

} while ($n < 0);

$result = fibonacci($n);

echo "Число Фибоначчи с номером $n: $result\n";