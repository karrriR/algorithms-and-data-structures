<?php
/*
3. Возведение в степень: Напишите функцию, которая рекурсивно возводит число x в степень n.
*/

function power(float $x, int $n) { // Рекурсивная функция возведения в степень

    if ($n == 0) { //условие остановки рекурсии
        return 1;
    }

    return $x * power($x, $n - 1);
}

$x = (float) readline("Введите число X: ");
$n = (int) readline("Введите степень N: ");

$result = power($x, $n);

echo "$x в степени $n равно: $result\n";