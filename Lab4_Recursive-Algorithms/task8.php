<?php
/*
8. Подсчет количества цифр в числе: Напишите функцию, которая рекурсивно подсчитывает количество цифр в заданном числе.
*/

function countDigits($n) {
    $n = abs($n);

    if ($n < 10) { //если число однозначное, возвращаем 1
        return 1;
    }

    return 1 + countDigits(intdiv($n, 10)); //убираем последнюю цифру и увеличиваем счетчик
}

$n = (int) readline("Введите целое число: ");

$result = countDigits($n);

echo "Количество цифр: $result\n";