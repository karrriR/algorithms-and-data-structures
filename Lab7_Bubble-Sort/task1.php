<?php
//Сортировка пузырьком

$n = (int) readline("Введите количество элементов массива: ");

$a = [];

// pаполняем массив случайными числами
for ($i = 0; $i < $n; $i++) {
    $a[$i] = rand(1, 100);
}

echo "\nИсходный массив:\n";
echo implode(" ", $a) . "\n\n";

// Сортировка пузырьком
for ($i = 0; $i < $n - 1; $i++) {
    echo "Проход " . ($i + 1) . ":\n";

    for ($j = 0; $j < $n - $i - 1; $j++) {

        echo "Сравниваем " . $a[$j] . " и " . $a[$j + 1];

        if ($a[$j] > $a[$j + 1]) {

            // Меняем элементы местами
            $temp = $a[$j];
            $a[$j] = $a[$j + 1];
            $a[$j + 1] = $temp;

            echo " -> меняем местами\n";
        } else {
            echo " -> оставляем как есть\n";
        }

        // Выводим массив после каждого сравнения
        echo implode(" ", $a) . "\n";
    }

    echo "\n";
}

echo "Отсортированный массив:\n";
echo implode(" ", $a) . "\n";
