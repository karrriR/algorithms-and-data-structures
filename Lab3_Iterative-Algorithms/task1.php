<?php
/*
1. Дано вещественное число — цена 1 кг конфет. Вывести стоимость 0.1, 0.2, . . . , 1 кг конфет.
*/

$price = (float) readline("Введите цену 1 кг конфет: ");

$i = 1; // начало счетчика типо 0.1 0.2 и тд

while ($i <= 10) {
    $weight = $i / 10; // вес конфет
    $cost = $price * $weight; // стоимость за текущую граммовку

    echo "$weight кг конфет стоят $cost руб.\n";
    $i++;
}