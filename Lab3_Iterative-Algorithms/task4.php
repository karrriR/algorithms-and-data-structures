<?php
/*
4. Дано вещественное число A и целое число N (> 0). Используя один цикл, найти сумму 1 + A + A2 + A3 + . . . + AN
*/

$a = (float) readline("Введите число A: ");
$n = (int) readline("Введите число N: ");

$sum = 1; // 1 тк 1 + A + A2...
$i = 1; // счетчик

while ($i <= $n) {
    $sum += $a ** $i;
    $i++;
}

echo "Сумма равна: $sum\n";