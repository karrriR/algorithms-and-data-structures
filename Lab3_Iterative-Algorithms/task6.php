<?php
/*
6. Даны целые положительные числа A и B (A < B). Вывести все целые числа от A до B включительно; 
при этом каждое число должно выводиться столько раз, каково его значение (например, число 3 выводится 3 раза).
*/

//проверка на A < B
do {
    $a = (int) readline("Введите число A: ");
    $b = (int) readline("Введите число B: ");
    if ($a >= $b) {
        echo "Ошибка! Число A должно быть меньше B.\n";
    }
} while ($a >= $b);

$i = $a; //счетчик начинается с числа которое введет юзер

while ($i <= $b) {
    $j = 1; // внутренний счетчик кол-ва вывода чисел

    while ($j <= $i) {
        echo "$i ";
        $j++;
    }

    echo "\n";

    $i++;
}