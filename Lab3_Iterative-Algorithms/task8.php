<?php
/*
8. Дано целое число N (> 1). Вывести наименьшее из целых чисел K, для которых сумма 1 + 2 + . . . + K будет больше или равна N, и саму эту сумму.
*/

// проверка на N (> 1)
do {
    $n = (int) readline("Введите число N: ");

    if ($n <= 1) {
        echo "Ошибка! N должно быть больше 1.\n";
    }

} while ($n <= 1);

$k = 0;
$sum = 0;

while ($sum < $n) {
    $k++;
    $sum += $k;
    echo "Текущая сумма = $sum\n";
}

echo "K = $k\n";
echo "Сумма = $sum\n";