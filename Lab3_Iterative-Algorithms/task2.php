<?php
/*
2. Дано целое число N (> 0). Найти произведение 1.1 · 1.2 · 1.3 · . . . (N сомножителей).
*/

$n = (int) readline("Введите число N: ");
$product = 1; // начальное знач. произведения
$i = 1; // счетчик

while ($i <= $n) {
    $product *= 1 + $i / 10; // 1 * 1 + 0.1; 1.1 * 1 + 1.2 и тд.
    $i++;
}

echo "Произведение равно: $product\n";