<?php
/*
5. Дано вещественное число A и целое число N (> 0). Используя один цикл, найти значение выражения 
1 − A + A2 − A3 + . . . ± AN . 
Условный оператор не использовать.
*/

$a = (float) readline("Введите число A: ");
$n = (int) readline("Введите число N: ");

$sum = 1; // тк выражение начинается с 1
$i = 1; // счетчик

$sign = -1; // - ставится тк после 1 в начале выражение стоит -

while ($i <= $n) {
    $sum += $sign * ($a ** $i); // 1 += -1 * ($a^1) и тд
    $sign *= -1; //меняем знак

    $i++;
}

echo "Сумма равна: $sum\n";