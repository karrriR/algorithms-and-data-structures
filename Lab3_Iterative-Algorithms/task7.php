<?php
/*
7. Даны положительные числа A и B (A > B). На отрезке длины A размещено максимально возможное 
количество отрезков длины B (без наложений). Не используя операции умножения и деления, найти длину незанятой части отрезка A.
*/

//проверка на A > B
do {
    $a = (float) readline("Введите число A: ");
    $b = (float) readline("Введите число B: ");

    if ($a <= 0 || $b <= 0 || $a <= $b) {
        echo "Ошибка! Числа должны быть положительными, а A должно быть больше B.\n";
    }

} while ($a <= 0 || $b <= 0 || $a <= $b);

while ($a >= $b) {
    $a -= $b;
}

echo "Незанятая часть отрезка: $a\n";