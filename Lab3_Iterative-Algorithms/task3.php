<?php
/*
3. Дано целое число N (> 0). Найти квадрат данного числа, используя для его вычисления следующую формулу: 
N2 = 1 + 3 + 5 + . . . + (2·N − 1). После добавления к сумме каждого слагаемого выводить текущее значение суммы
*/

$n = (int) readline("Введите число N: ");
$sum = 0; // 0 - так как начальное знач суммы 0
$i = 1; // счетчик (не 0 тк на него перемножаем)

while ($i <= $n) {
    $sum += 2 * $i - 1; // 0 += 2 * 1 - 1

    echo "Текущая сумма: $sum\n";

    $i++;
}

echo "Квадрат числа $n равен: $sum\n";