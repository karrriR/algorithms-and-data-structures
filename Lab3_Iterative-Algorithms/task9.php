<?php
/*
9. Начальный вклад в банке равен 1000 руб. Через каждый месяц размер вклада увеличивается на P процентов от имеющейся суммы 
(P — вещественное число, 0 < P < 25). По данному P определить, через сколько месяцев размер вклада превысит 1100 руб., 
и вывести найденное количество месяцев K (целое число) и итоговый размер вклада S (вещественное число).
*/

do { // проверка на 0 < P < 25
    $p = (float) readline("Введите процент P: ");

    if ($p <= 0 || $p >= 25) {
        echo "Ошибка! P должно быть больше 0 и меньше 25.\n";
    }

} while ($p <= 0 || $p >= 25);

$s = 1000; //начальный вклад
$k = 0; // начальное кол-во месяцев

while ($s <= 1100) {
    $s += $s * $p / 100;
    $k++;
}

echo "Количество месяцев: $k\n";
echo "Итоговая сумма: $s руб.\n";