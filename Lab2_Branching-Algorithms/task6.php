<?php
/*
6. Дано целое число, лежащее в диапазоне 1–999. Вывести его строку описание вида «четное двузначное число», «нечетное трехзначное число» и т. д.
*/

$a = (int) readline("Введите число от 1 до 999: ");

// Определение количества цифр
if ($a < 10) {
    $digits = "однозначное";
} elseif ($a < 100) {
    $digits = "двузначное";
} else {
    $digits = "трехзначное";
}

// Определение четности
$parity = ($a % 2 == 0) ? "четное" : "нечетное";

echo "$digits $parity число\n";