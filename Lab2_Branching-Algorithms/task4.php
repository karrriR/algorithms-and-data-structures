<?php
/*
4. Даны координаты точки, не лежащей на координатных осях OX и OY. Определить номер координатной четверти, в которой находится данная точка
*/
$x = (float) readline("Введите координату X: ");
$y = (float) readline("Введите координату Y: ");

// Определение четверти
if ($x > 0 && $y > 0) {
    echo "Точка находится в первой четверти.\n";
} elseif ($x < 0 && $y > 0) {
    echo "Точка находится во второй четверти.\n";
} elseif ($x < 0 && $y < 0) {
    echo "Точка находится в третьей четверти.\n";
} else {
    echo "Точка находится в четвертой четверти.\n";
}