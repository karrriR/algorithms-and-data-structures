<?php
/*
2. Даны три числа. Найти сумму двух наибольших из них
*/

$a = (float) readline("Введите первое число: ");
$b = (float) readline("Введите второе число: ");
$c = (float) readline("Введите третье число: ");

// Проверка на наименьшее число
if ($a <= $b && $a <= $c) {
    $sum = $b + $c;
} elseif ($b <= $a && $b <= $c) {
    $sum = $a + $c;
} else {
    $sum = $a + $b;
}

echo "Сумма двух наибольших чисел = $sum\n";