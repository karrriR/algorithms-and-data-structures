<?php
/*
9. Дано целое число в диапазоне 100–999. Вывести строку-описание данного числа, например: 256 — «двести пятьдесят шесть», 814 — «восемьсот четырнадцать».
*/

$n = (int) readline("Введите число от 100 до 999: ");

// Получение сотен, десятков и единиц
$hundreds = (int) ($n / 100);
$tens = (int) (($n % 100) / 10);
$units = $n % 10;

// Определение сотен
$hundredWord = match ($hundreds) {
    1 => "сто",
    2 => "двести",
    3 => "триста",
    4 => "четыреста",
    5 => "пятьсот",
    6 => "шестьсот",
    7 => "семьсот",
    8 => "восемьсот",
    9 => "девятьсот"
};

// Определение десятков
if ($tens == 1) {
    $tensWord = match ($n % 100) {
        10 => "десять",
        11 => "одиннадцать",
        12 => "двенадцать",
        13 => "тринадцать",
        14 => "четырнадцать",
        15 => "пятнадцать",
        16 => "шестнадцать",
        17 => "семнадцать",
        18 => "восемнадцать",
        19 => "девятнадцать"
    };
    $unitWord = "";
    
} else {
    $tensWord = match ($tens) {
        0 => "",
        2 => "двадцать",
        3 => "тридцать",
        4 => "сорок",
        5 => "пятьдесят",
        6 => "шестьдесят",
        7 => "семьдесят",
        8 => "восемьдесят",
        9 => "девяносто"
    };

    // Определение единиц
    $unitWord = match ($units) {
        0 => "",
        1 => "один",
        2 => "два",
        3 => "три",
        4 => "четыре",
        5 => "пять",
        6 => "шесть",
        7 => "семь",
        8 => "восемь",
        9 => "девять"
    };
}

echo trim("$hundredWord $tensWord $unitWord") . "\n";