<?php
/*
10. В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов, обозначаемых названиями цвета: 
зеленый, красный, желтый, белый и черный. В каждом подцикле годы носят названия животных: 
крысы, коровы, тигра, зайца, дракона, змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. 
По номеру года определить его название, если 1984 год — начало цикла: «год зеленой крысы».
*/

$year = (int) readline("Введите год: ");

// положение года в 60-летнем цикле
$offset = (($year - 1984) % 60 + 60) % 60;

// цвет (меняется каждые 12 лет)
$colorIndex = intdiv($offset, 12);

$color = match ($colorIndex) {
    0 => "зеленой",
    1 => "красной",
    2 => "желтой",
    3 => "белой",
    4 => "черной"
};

// животное (меняется каждый год)
$animalIndex = $offset % 12;

$animal = match ($animalIndex) {
    0 => "крысы",
    1 => "коровы",
    2 => "тигра",
    3 => "зайца",
    4 => "дракона",
    5 => "змеи",
    6 => "лошади",
    7 => "овцы",
    8 => "обезьяны",
    9 => "курицы",
    10 => "собаки",
    11 => "свиньи"
};

echo "Год $year — год $color $animal\n";