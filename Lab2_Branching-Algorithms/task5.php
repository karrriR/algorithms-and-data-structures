<?php
/*
5. Дано целое число. Вывести его строку-описание вида «отрицательное четное число», «нулевое число», «положительное нечетное число» и т. д.
*/

$a = (int) readline("Введите целое число: ");

// Проверка числа
if ($a == 0) {
    echo "Нулевое число\n";
} elseif ($a > 0 && $a % 2 == 0) {
    echo "Положительное четное число\n";
} elseif ($a > 0 && $a % 2 != 0) {
    echo "Положительное нечетное число\n";
} elseif ($a < 0 && $a % 2 == 0) {
    echo "Отрицательное четное число\n";
} else {
    echo "Отрицательное нечетное число\n";
}