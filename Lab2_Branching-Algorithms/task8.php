<?php
/*
8. Дано целое число в диапазоне 10–40, определяющее количество учебных заданий по некоторой теме. 
Вывести строку-описание указанного количества заданий, обеспечив правильное согласование числа со словами «учебное задание», 
например: 18 — «восемнадцать учебных заданий».
*/

$n = (int) readline("Введите количество заданий (10–40): ");

// Разделение на десятки и единицы
$tens = (int) ($n / 10);
$units = $n % 10;

// Определение чисел от 10 до 19 (не подходят под разделение выше поэтому отдельная проверка)
if ($n >= 10 && $n <= 19) {
    $number = [
        10 => "десять", 11 => "одиннадцать",
        12 => "двенадцать", 13 => "тринадцать",
        14 => "четырнадцать", 15 => "пятнадцать",
        16 => "шестнадцать", 17 => "семнадцать",
        18 => "восемнадцать", 19 => "девятнадцать"
    ];
    $word = $number[$n];

} else {

    // Определение десятков
    $word = match ($tens) {
        2 => "двадцать",
        3 => "тридцать",
        4 => "сорок"
    };

    // Определение единиц
    $unit = match ($units) {
        1 => "одно",
        2 => "два",
        3 => "три",
        4 => "четыре",
        5 => "пять",
        6 => "шесть",
        7 => "семь",
        8 => "восемь",
        9 => "девять",
        default => ""
    };

    // Соединение десятков и единиц
    $word = $word . " " . $unit;
}

// Определение окончания
if (($n >= 11 && $n <= 19) || $units >= 5 || $units == 0) {
    $ending = "учебных заданий";
} elseif ($units == 1) {
    $ending = "учебное задание";
} else {
    $ending = "учебных задания";
}

echo "$word $ending\n";