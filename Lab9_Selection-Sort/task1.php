<?php
//Сортировка выбором

$n = (int) readline("Введите количество элементов массива: ");

$a = [];

// заполнение массива
for ($i = 0; $i < $n; $i++) {
    $a[$i] = rand(1, 100);
}

echo "\nИсходный массив:\n";
echo implode(" ", $a) . "\n\n";

// Сортировка выбором
for ($i = 0; $i < $n - 1; $i++) {

    // Считаем текущий элемент минимальным
    $minIndex = $i;

    echo "Ищем минимум начиная с числа " . $a[$i] . "\n";

    // Ищем минимальный элемент в оставшейся части массива
    for ($j = $i + 1; $j < $n; $j++) {

        echo "Сравниваем " . $a[$minIndex] . " и " . $a[$j] . "\n";

        if ($a[$j] < $a[$minIndex]) {
            $minIndex = $j;
            echo "Нашли новый минимум: " . $a[$minIndex] . "\n";
        }
    }

    // Меняем текущий элемент с минимальным
    if ($minIndex != $i) {
        $temp = $a[$i];
        $a[$i] = $a[$minIndex];
        $a[$minIndex] = $temp;

        echo "Меняем местами элементы\n";
    } else {
        echo "Минимальный элемент уже на своём месте\n";
    }

    echo "Массив: " . implode(" ", $a) . "\n\n";
}

echo "Отсортированный массив:\n";
echo implode(" ", $a) . "\n";