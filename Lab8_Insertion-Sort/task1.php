<?php
// Сортировка вставками

$n = (int) readline("Введите количество элементов массива: ");

$a = [];

// заполнение массива
for ($i = 0; $i < $n; $i++) {
    $a[$i] = rand(1, 100);
}

echo "\nИсходный массив:\n";
echo implode(" ", $a) . "\n\n";

// Сортировка вставками
for ($i = 1; $i < $n; $i++) {

    $current = $a[$i];
    $j = $i - 1;

    echo "Берём число $current\n";

    // Сдвигаем большие элементы вправо
    while ($j >= 0 && $a[$j] > $current) {
        echo "  $a[$j] > $current, сдвигаем $a[$j] вправо\n";

        $a[$j + 1] = $a[$j];
        $j--;
    }

    // Вставляем число на освободившееся место
    $a[$j + 1] = $current;

    echo "  Вставляем $current на место\n";
    echo "  Массив: " . implode(" ", $a) . "\n\n";
}

echo "Отсортированный массив:\n";
echo implode(" ", $a) . "\n";