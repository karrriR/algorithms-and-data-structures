<?php
/*
3. Даны целые числа N (> 2), A и B. Сформировать и вывести целочисленный массив размера N, 
первый элемент которого равен A, второй равен B, а каждый последующий элемент равен сумме всех предыдущих
*/

$n = (int) readline("Введите размер массива N: ");
$a = (int) readline("Введите первый элемент A: ");
$b = (int) readline("Введите второй элемент B: ");

$arr = [];

$arr[0] = $a;
$arr[1] = $b;

for ($i = 2; $i < $n; $i++) { //выбирает элемент, который нужно вычислить
    $arr[$i] = 0;

    for ($j = 0; $j < $i; $j++) {//проходит по всем предыдущим элементам и складывает их
        $arr[$i] += $arr[$j];
    }
}

echo "Элементы массива: ";

for ($i = 0; $i < $n; $i++) { //вывод
    echo $arr[$i] . " ";
}

echo "\n";