<?php
/*
9. Дан массив размера N. Найти номер его последнего локального максимума (локальный максимум — это элемент, который больше любого из своих соседей).
Локальный максимум — это элемент, который больше своих соседей.
*/

$n = (int) readline("Введите размер массива N: ");

$a = [];

for ($i = 0; $i < $n; $i++) {
    $a[] = rand(1, 100);
}

echo "Исходный массив: " . implode(", ", $a) . "\n";

// переменная для хранения номера последнего локального максимума
$lastMax = 0;

// проверка элементов массива
for ($i = 1; $i < $n - 1; $i++) {
    if ($a[$i] > $a[$i - 1] && $a[$i] > $a[$i + 1]) {
        $lastMax = $i + 1;
    }
}

if ($lastMax != 0) {
    echo "Номер последнего локального максимума: " . $lastMax . " — значение: " . $a[$lastMax - 1] . "\n";
} else {
    echo "Локальных максимумов нет\n";
}