<?php
/*
7. Дан целочисленный массив размера N, не содержащий одинаковых чисел. 
Проверить, образуют ли его элементы арифметическую прогрессию. Если образуют, то вывести разность прогрессии, если нет — вывести 0.
*/

$n = (int) readline("Введите размер массива N: ");

$a = [];

for ($i = 0; $i < $n; $i++) {
    $a[] = (int) readline("Введите элемент массива: ");
}

echo "Исходный массив: " . implode(", ", $a) . "\n";

// разность между первыми двумя элементами
$d = $a[1] - $a[0];

$isProgression = true;

// проверка разности между соседними элементами
for ($i = 1; $i < $n - 1; $i++) {
    if ($a[$i + 1] - $a[$i] != $d) {
        $isProgression = false;
        break;
    }
}

if ($isProgression) {
    echo "Разность прогрессии: $d\n";
} else {
    echo "0\n";
}