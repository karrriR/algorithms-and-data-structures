<?php
/*
6. Дан массив размера N и целые числа K и L (1 ≤ K ≤ L ≤ N). Найти среднее арифметическое элементов массива с номерами от K до L включительно.
*/

$n = (int) readline("Введите размер массива N: ");

$a = [];

for ($i = 0; $i < $n; $i++) {//заполнение массива
    $a[] = rand(1, 100);
}

echo "Исходный массив: " . implode(", ", $a) . "\n";

// проверка 
do {
    $k = (int) readline("Введите K (от 1 до $n): ");
    $l = (int) readline("Введите L (от $k до $n): ");

    if ($k < 1 || $l > $n || $k > $l) {
        echo "Ошибка! Проверьте значения K и L.\n";
    }
} while ($k < 1 || $l > $n || $k > $l);

// сумма элементов от K до L
$sum = 0;

for ($i = $k - 1; $i < $l; $i++) {
    $sum += $a[$i];
}

// среднее арифметическое
$count = $l - $k + 1;
$average = $sum / $count;

echo "Среднее арифметическое: $average\n";