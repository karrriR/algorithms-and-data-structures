<?php
/*
8. Дан массив A размера N. Найти минимальный элемент из его элементов с четными номерами: A2, A4, A6,
*/

$n = (int) readline("Введите размер массива N: ");

$a = [];

for ($i = 0; $i < $n; $i++) {//заполнение массива
    $a[] = rand(1, 100);
}

echo "Исходный массив: " . implode(", ", $a) . "\n";

// первый элемент с чётным номером
$min = $a[1];

// минимальный элемент среди остальных элементов с чётными номерами
for ($i = 3; $i < $n; $i += 2) {
    if ($a[$i] < $min) {
        $min = $a[$i];
    }
}

echo "Минимальный элемент с чётным номером: $min\n";