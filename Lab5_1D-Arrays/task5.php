<?php
/*
5. Дан массив A размера N. Вывести вначале его элементы с нечетными номерами в порядке возрастания номеров, 
а затем — элементы с четными номерами в порядке убывания номеров
*/

$n = (int) readline("Введите размер массива N: ");

$a = [];

for ($i = 0; $i < $n; $i++) {//заполнение массива
    $a[] = rand(1, 100);
}

echo "Исходный массив: " . implode(", ", $a) . "\n"; //объединение в одну строку и вывод

echo "Результат: ";

// Вывод элементов с нечётными номерами
for ($i = 0; $i < $n; $i += 2) {
    echo $a[$i] . " ";
}

// Вывод элементов с чётными номерами в обратном порядке
for ($i = $n - 1; $i >= 1; $i -= 2) {
    echo $a[$i] . " ";
}

echo "\n";