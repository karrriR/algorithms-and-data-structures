<?php
/*
2. Дано целое число N (> 1), а также первый член A и знаменатель D геометрической прогрессии. 
Сформировать и вывести массив размера N, содержащий N первых членов данной прогрессии: A, A·D, A·D2 , A·D3 , . . .
*/

$n = (int) readline("Введите размер массива N: ");
$a = (float) readline("Введите первый член A: ");
$d = (float) readline("Введите знаменатель D: ");

$arr = [];

$arr[0] = $a;

for ($i = 1; $i < $n; $i++) { //заполнение
    $arr[$i] = $arr[$i - 1] * $d;
}

echo "Элементы массива: ";

for ($i = 0; $i < $n; $i++) { //вывод
    echo $arr[$i] . " ";
}

echo "\n";