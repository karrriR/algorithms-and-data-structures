<?php
/*
10. Дан целочисленный массив размера N, содержащий ровно два одинаковых элемента. Найти номера одинаковых элементов и вывести эти номера в порядке возрастания
*/

$n = (int) readline("Введите размер массива N: ");
$a = [];

for ($i = 0; $i < $n; $i++) {
    $a[] = (int) readline("Введите элемент массива: ");
}

echo "Исходный массив: " . implode(", ", $a) . "\n";

// одинаковые элементы
for ($i = 0; $i < $n; $i++) { //элемент массива для сравнения с остальными
    for ($j = $i + 1; $j < $n; $j++) {//перебор элементов, которые находятся после выбранного элемента
        if ($a[$i] == $a[$j]) {
            echo "Номера одинаковых элементов: " . ($i + 1) . " и " . ($j + 1) . "\n";
        }
    }
}