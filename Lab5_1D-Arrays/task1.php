<?php
/*
1. Дано целое число N (> 0). Сформировать и вывести целочисленный массив размера N, содержащий N первых положительных нечетных чисел: 1, 3, 5, . . . .
*/
$n = (int) readline("Введите размер массива N: ");

$arr = [];

for ($i = 0; $i < $n; $i++) { //заполнение массива
    $arr[$i] = 2 * $i + 1;
}

echo "Элементы массива: ";

for ($i = 0; $i < $n; $i++) { // вывод
    echo $arr[$i] . " ";
}

echo "\n";