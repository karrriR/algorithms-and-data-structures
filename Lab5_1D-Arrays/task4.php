<?php
/*
4. Дан массив A размера N. Вывести его элементы в следующем порядке: A1, AN , A2, AN−1, A3, AN−2,
*/

// ввод размера массива N с клавиатуры
do {
    $n = (int) readline("Введите размер массива N (больше 0): ");
} while ($n <= 0);

// заполнение одномерного массива случайными числами через for
$a = [];
for ($i = 0; $i < $n; $i++) {
    $a[] = rand(1, 100);
}

echo "Исходный массив: " . implode(", ", $a) . "\n"; // исходный массив, все элементы которого объединили в одну строку, вставляя между ними указанный разделитель

// элементы в порядке: A1, AN, A2, AN-1... 
//intdiv() выполняет целочисленное деление
echo "Результат: ";
for ($i = 0; $i < intdiv($n, 2); $i++) {
    echo $a[$i] . " ";
    echo $a[$n - 1 - $i] . " ";
}

// если N нечётное, выводим центральный элемент
if ($n % 2 !== 0) {
    echo $a[intdiv($n, 2)];
}
echo "\n";