<?php
/*
Используя словесное описание реализовать работу с очередью
Принцип очереди: кто пришёл первым, тот выходит первым.
*/

$queue = []; // пустая очередь
 $num = 2; // число для проверки наличия в очереди

foreach ([1, 2, 3, 7, 9] as $number) { // заполнение очереди 
    $queue[] = $number;
}

while (!empty($queue)) {
    // текущая очередь на начало и кол-во элементов
    echo "Очередь: " . implode(' ', $queue) . "\n";
    echo "Размер очереди: " . count($queue) . "\n";
    echo "Первый элемент: $queue[0] \n"; // первый элемент в очереди - не удаляем пока

    // проверка на сущ числа в очереди
    echo in_array($num, $queue, true) ? "Число $num есть в очереди.\n" : "В очереди нет числа $num.\n";

    $item = array_shift($queue); // берем первый элемент и удаляем его из очереди
    echo "Забрали из очереди: $item\n";
    echo "\n";
}

echo "Очередь пуста. Размер: " . count($queue) . "\n";