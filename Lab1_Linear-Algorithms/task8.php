<?php 
/*
8.	Даны три точки A, B, C на числовой оси. Точка C расположена между точками A и B. Найти произведение длин отрезков AC и BC
*/


// Ввод точек
$a = (float) readline("Введите координату точки A: ");
$b = (float) readline("Введите координату точки B: ");
$c = (float) readline("Введите координату точки C: ");

// Нахождение длин отрезков
$ac = abs($c - $a);
$bc = abs($b - $c);

$prod = $ac * $bc;

echo "Произведение длин отрезков = $prod\n";