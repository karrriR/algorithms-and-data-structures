<?php 
/*
6.	Найти расстояние между двумя точками с заданными координатами (x1, y1) и (x2, y2)
*/

// Координаты 1 точки
$x1 = (float) readline("Введите x1: ");
$y1 = (float) readline("Введите y1: ");

// Координаты 2 точки
$x2 = (float) readline("Введите x2: ");
$y2 = (float) readline("Введите y2: ");

$distance = sqrt(($x2 - $x1) ** 2 + ($y2 - $y1) ** 2); // вычисление расстояния

echo "Расстояние между точками = $distance\n";