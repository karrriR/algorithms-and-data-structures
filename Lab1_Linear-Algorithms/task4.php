<?php 
/*
4.	Даны два ненулевых числа. Найти сумму, разность, произведение и частное их квадратов.
*/

$a = (float) readline("Введите число a: ");
while ($a == 0) { // проверка на ноль у 1 числа
    echo "Число не должно быть нулём!\n";
    $a = (float) readline("Введите число a: ");
}

$b = (float) readline("Введите число b: ");
while ($b == 0) { // проверка на ноль у 2 числа
    echo "Число не должно быть нулём!\n";
    $b = (float) readline("Введите число b: ");
}

// Вычисление квадратов чисел
$a2 = $a ** 2;
$b2 = $b ** 2;

// Основные вычисления 
$sum = $a2 + $b2;
$diff = $a2 - $b2;
$prod = $a2 * $b2;
$div = $a2 / $b2;

echo "Сумма квадратов = $sum\n";
echo "Разность квадратов = $diff\n";
echo "Произведение квадратов = $prod\n";
echo "Частное квадратов = $div\n";
