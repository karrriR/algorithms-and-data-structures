<?php 
/*
7.	Даны три точки A, B, C на числовой оси. Найти длины отрезков AC и BC и их сумму.
*/

// Ввод точек
$a = (float) readline("Введите точку A: ");
$b = (float) readline("Введите точку B: ");
$c = (float) readline("Введите точку C: ");

// Нахождение длин отрезков
$ac = abs($c - $a);
$bc = abs($c - $b);

// Нахождение суммы длин отрезкоы
$sum = $ac + $bc;

echo "Длина AC = $ac\n";
echo "Длина BC = $bc\n";
echo "Сумма длин = $sum\n";