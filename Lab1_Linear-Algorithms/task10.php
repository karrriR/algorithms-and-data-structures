<?php
/*
10.	Даны координаты трех вершин треугольника: (x1, y1), (x2, y2), (x3, y3). Найти его периметр и площадь
*/

// Ввод координат точки A B C
$x1 = (float) readline("Введите x1: ");
$y1 = (float) readline("Введите y1: ");

$x2 = (float) readline("Введите x2: ");
$y2 = (float) readline("Введите y2: ");

$x3 = (float) readline("Введите x3: ");
$y3 = (float) readline("Введите y3: ");

// Нахождение длин сторон
$ab = sqrt(($x2 - $x1) ** 2 + ($y2 - $y1) ** 2);
$bc = sqrt(($x3 - $x2) ** 2 + ($y3 - $y2) ** 2);
$ca = sqrt(($x1 - $x3) ** 2 + ($y1 - $y3) ** 2);

// Нахождение периметра и площади
$p = $ab + $bc + $ca;
$s = abs(($x2 - $x1) * ($y3 - $y1) - ($x3 - $x1) * ($y2 - $y1)) / 2;

echo "Длина стороны AB = $ab\n";
echo "Длина стороны BC = $bc\n";
echo "Длина стороны CA = $ca\n";
echo "Периметр треугольника = $p\n";
echo "Площадь треугольника = $s\n";