<?php 
/*
1.	Даны стороны прямоугольника a и b. Найти его площадь S = a·b и периметр P = 2·(a + b).
*/

$a = (float) readline("Введите сторону прямоугольника a: ");
$b = (float) readline("Введите сторону прямоугольника b: ");

$S = $a * $b; // - площадь
$P = 2 * ($a + $b); // - периметр

echo "Площадь прямоугольника S = $S\n";
echo "Периметр прямоугольника P = $P";
