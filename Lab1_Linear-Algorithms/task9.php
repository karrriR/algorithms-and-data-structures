<?php 
/*
9.	Даны координаты двух противоположных вершин прямоугольника: (x1, y1), (x2, y2). 
Стороны прямоугольника параллельны осям координат. Найти периметр и площадь данного прямоугольника.
*/

// Точки первой и второй вершины
$x1 = (float) readline("Введите x1: ");
$y1 = (float) readline("Введите y1: ");
$x2 = (float) readline("Введите x2: ");
$y2 = (float) readline("Введите y2: ");

// Нахождение длины и ширины прямоугольника
$a = abs($x2 - $x1);
$b = abs($y2 - $y1);

// Нахождение площади и периметра
$s = $a * $b;
$p = 2 * ($a + $b);

echo "Площадь прямоугольника = $s\n";
echo "Периметр прямоугольника = $p\n";