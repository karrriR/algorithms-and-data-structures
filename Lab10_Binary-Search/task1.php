<?php
/*
Бинарный поиск - это алгоритм, используемый для поиска значения в отсортированном массиве или списке. Он работает на основе принципа "разделяй и властвуй".
Алгоритм бинарного поиска следующий:
1. Установите начальные значения для левой (left) и правой (right) границ поиска. Левая граница будет равна 0, а правая граница - последнему индексу в массиве.
2. Пока левая граница меньше или равна правой границе, выполняйте следующие шаги:
   a. Найдите средний элемент массива, вычислив индекс как (left + right) // 2.
   b. Если значение среднего элемента равно искомому значению, верните индекс среднего элемента.
   c. Если значение среднего элемента больше искомого значения, обновите правую границу на (средний индекс - 1).
   d. Если значение среднего элемента меньше искомого значения, обновите левую границу на (средний индекс + 1).
3. Если значение не найдено, верните -1.
*/

function binarySearch($numbers, $target)
{
    $left = 0;                    // Индекс первого элемента
    $right = count($numbers) - 1; // Индекс последнего элемента

    // продолжаем поиск, пока между границами есть элементы
    while ($left <= $right) {
        // intdiv делит нацело intdiv(5, 2) = 2
        $middle = intdiv($left + $right, 2);

        // если нашли нужное число, возвращаем его индекс
        if ($numbers[$middle] === $target) {
            return $middle;
        }

        if ($numbers[$middle] < $target) {
            // нужное число может быть только правее середины
            $left = $middle + 1;
        } else {
            // нужное число может быть только левее середины
            $right = $middle - 1;
        }
    }

    // если границы пересеклись, искомого числа нет в массиве
    return -1;
}

$numbers = [2, 5, 8, 12, 18, 23, 38];
$target = 16;
$index = binarySearch($numbers, $target);

if ($index === -1) {
    echo "Число $target не найдено.";
} else {
    echo "Число $target найдено. Индекс - $index.";
}