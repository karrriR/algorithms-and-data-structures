<?php
/*
10. Дана квадратная матрица A порядка M. Найти сумму элементов каждой ее диагонали, параллельной главной (начиная с одноэлементной диагонали).
*/

$m = (int) readline("Введите размер квадратной матрицы M: ");

$a = [];

// заполнение матрицы
for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $m; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

// исходник
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $m; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// суммы диагоналей выше главной
for ($j = $m - 1; $j >= 0; $j--) {
    $sum = 0;

    for ($i = 0; $i < $m - $j; $i++) {
        $sum += $a[$i][$i + $j];
    }

    echo "Сумма диагонали: $sum\n";
}

// суммы диагоналей ниже главной
for ($i = 1; $i < $m; $i++) {
    $sum = 0;

    for ($j = 0; $j < $m - $i; $j++) {
        $sum += $a[$i + $j][$j];
    }

    echo "Сумма диагонали: $sum\n";
}
