<?php
/*
1. Дана квадратная матрица A порядка M (M — нечетное число). 
Начиная с элемента A1,1 и перемещаясь против часовой стрелки, вывести все ее элементы по спирали: 
первый столбец, последняя строка, последний столбец в обратном порядке, первая строка в обратном порядке, 
оставшиеся элементы второго столбца и т. д.; последним выводится центральный элемент матрицы.
*/

// проверка на порядок квадратной матрицы
do {
    $m = (int) readline("Введите нечётный порядок матрицы M: ");

    if ($m <= 0 || $m % 2 == 0) {
        echo "Ошибка! M должно быть положительным нечётным числом.\n";
    }
} while ($m <= 0 || $m % 2 == 0);

// заполнение матрицы
$a = [];

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $m; $j++) {
        $a[$i][$j] = rand(1, 99);
    }
}

// вывод исходной матрицу
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $m; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// указание границы матрицы
$top = 0;
$bottom = $m - 1;
$left = 0;
$right = $m - 1;

echo "Элементы по спирали: ";

// обход матрицы против часовой стрелки
while ($top <= $bottom && $left <= $right) {

    // первый столбец сверху вниз
    for ($i = $top; $i <= $bottom; $i++) {
        echo $a[$i][$left] . " ";
    }

    // последняя строка слева направо
    for ($j = $left + 1; $j <= $right; $j++) {
        echo $a[$bottom][$j] . " ";
    }

    // последний столбец снизу вверх
    if ($left < $right) {
        for ($i = $bottom - 1; $i >= $top; $i--) {
            echo $a[$i][$right] . " ";
        }
    }

    // первая строка справа налево
    if ($top < $bottom) {
        for ($j = $right - 1; $j > $left; $j--) {
            echo $a[$top][$j] . " ";
        }
    }

    // переход к внутренней части матрицы
    $top++;
    $bottom--;
    $left++;
    $right--;
}

echo "\n";
