<?php
/*
6. Дана матрица размера M × N. Преобразовать матрицу, поменяв местами минимальный и максимальный элемент в каждой строке.
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

$a = [];

// заполнение матрицы
for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

// исходник
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// нахождение минимума и максимума в каждой строке
for ($i = 0; $i < $m; $i++) {
    $minIndex = 0;
    $maxIndex = 0;

    for ($j = 1; $j < $n; $j++) {
        if ($a[$i][$j] < $a[$i][$minIndex]) {
            $minIndex = $j;
        }

        if ($a[$i][$j] > $a[$i][$maxIndex]) {
            $maxIndex = $j;
        }
    }

    // минимум и максимум местами
    $temp = $a[$i][$minIndex];
    $a[$i][$minIndex] = $a[$i][$maxIndex];
    $a[$i][$maxIndex] = $temp;
}

// вывод измененной матрицу
echo "Матрица после замены:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}
