<?php
/*
5. Дана целочисленная матрица размера M × N. Найти номер первого из ее столбцов, содержащих только нечетные числа. Если таких столбцов нет, то вывести 0.
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

//заполнение матрицы
$a = [];

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

// исходник
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// переменная для хранения номера первого подходящего столбца
$result = 0;

// проверка стробцов
for ($j = 0; $j < $n; $j++) {
    $isOdd = true;

    // проверка всех элементов текущего столбца
    for ($i = 0; $i < $m; $i++) {
        if ($a[$i][$j] % 2 == 0) {
            $isOdd = false;
            break;
        }
    }

    // проверка если все элементы нечётные, запоминаем номер столбца
    if ($isOdd) {
        $result = $j + 1;
        break;
    }
}

echo "Номер первого столбца, содержащего только нечётные числа: $result\n";