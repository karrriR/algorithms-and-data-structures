<?php
/*
4. Дана матрица размера M × N. В каждом ее столбце найти количество элементов, больших среднего арифметического всех элементов этого столбца
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

// заполнение матрицы
$a = [];

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

// вывод исходника
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// цикл на каждый столбец
for ($j = 0; $j < $n; $j++) {
    $sum = 0;

    // нахождение суммы элементов столбца
    for ($i = 0; $i < $m; $i++) {
        $sum += $a[$i][$j];
    }

    // среднее арифметическое
    $average = $sum / $m;

    // элементы, которые больше среднего
    $count = 0;

    for ($i = 0; $i < $m; $i++) {
        if ($a[$i][$j] > $average) {
            $count++;
        }
    }

    // вывод результата для текущего столбца
    echo "Столбец " . ($j + 1) . ": $count элементов больше среднего ($average)\n";
}
