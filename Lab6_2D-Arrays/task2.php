<?php
/*
2. Дана матрица размера M × N и целое число K (1 ≤ K ≤ M). Найти сумму и произведение элементов K-й строки данной матрицы.
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

// заполнение матрицы
$a = [];

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 10);
    }
}

// вывод матрицы исходной
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// проверка на ввод номера строки K
do {
    $k = (int) readline("Введите номер строки K (от 1 до $m): ");

    if ($k < 1 || $k > $m) {
        echo "Ошибка! Такой строки нет.\n";
    }
} while ($k < 1 || $k > $m);

// нахождение суммы и произведения элементов выбранной строки
$sum = 0;
$product = 1;

for ($j = 0; $j < $n; $j++) {
    $sum += $a[$k - 1][$j];
    $product *= $a[$k - 1][$j];
}

echo "Сумма элементов строки $k: $sum\n";
echo "Произведение элементов строки $k: $product\n";
