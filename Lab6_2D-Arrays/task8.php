<?php
/*
8. Дана матрица размера M × N (M и N — четные числа). Поменять местами левую верхнюю и правую нижнюю четверти матрицы
*/

$m = (int) readline("Введите количество строк M (чётное): ");
$n = (int) readline("Введите количество столбцов N (чётное): ");

$a = [];

// заполнение матрицы
for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

//исходник
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// меняем местами верхнюю левую и нижнюю правую четверти
for ($i = 0; $i < $m / 2; $i++) {
    for ($j = 0; $j < $n / 2; $j++) {
        $temp = $a[$i][$j];
        $a[$i][$j] = $a[$i + $m / 2][$j + $n / 2];
        $a[$i + $m / 2][$j + $n / 2] = $temp;
    }
}

// измененная матрица
echo "Матрица после замены четвертей:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}
