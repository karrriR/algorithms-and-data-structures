<?php
/*
3. Дана матрица размера M × N. Найти номер ее столбца с наименьшим произведением элементов и вывести данный номер, а также значение наименьшего произведения.
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

// заполнение матрицы
$a = [];

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 10);
    }
}

// вывод матрицы исходной
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// нахождение произведения первого столбца
$minProduct = 1;

for ($i = 0; $i < $m; $i++) {
    $minProduct *= $a[$i][0];
}

$minColumn = 1;

// проверка остальных столбцов
for ($j = 1; $j < $n; $j++) {
    $product = 1;

    for ($i = 0; $i < $m; $i++) {
        $product *= $a[$i][$j];
    }

    if ($product < $minProduct) {
        $minProduct = $product;
        $minColumn = $j + 1;
    }
}

echo "Номер столбца с наименьшим произведением: $minColumn\n";
echo "Наименьшее произведение: $minProduct\n";
