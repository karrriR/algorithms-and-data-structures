<?php
/*
9. Дана матрица размера M × N. Упорядочить ее строки так, чтобы их первые элементы образовывали возрастающую последовательность.
*/

$m = (int) readline("Введите количество строк M: ");
$n = (int) readline("Введите количество столбцов N: ");

$a = [];

// заполнение матрицы
for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        $a[$i][$j] = rand(1, 100);
    }
}

// исходник
echo "Исходная матрица:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}

// сортируем строки по первым элементам
for ($i = 0; $i < $m - 1; $i++) {
    for ($j = 0; $j < $m - $i - 1; $j++) {
        if ($a[$j][0] > $a[$j + 1][0]) {
            $temp = $a[$j];
            $a[$j] = $a[$j + 1];
            $a[$j + 1] = $temp;
        }
    }
}

// вывод отсортированной матрицу
echo "Матрица после сортировки:\n";

for ($i = 0; $i < $m; $i++) {
    for ($j = 0; $j < $n; $j++) {
        echo $a[$i][$j] . "\t";
    }
    echo "\n";
}
